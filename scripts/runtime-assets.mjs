import { readFile, mkdir, writeFile, readdir, unlink } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import ts from 'typescript';
const manifest = JSON.parse(await readFile(new URL('../vendor/dos/manifest.json', import.meta.url), 'utf8'));
const root = new URL('../public/runtimes/js-dos/8.5.3/', import.meta.url);
await mkdir(root, { recursive: true });
for (const [name, hash] of Object.entries(manifest.assets)) {
  const bytes = await readFile(new URL(`../node_modules/emulators/dist/${name}`, import.meta.url));
  if (createHash('sha256').update(bytes).digest('hex') !== hash) throw new Error(`Audited runtime asset mismatch: ${name}`);
  await writeFile(new URL(name, root), bytes);
}
// The host has a separate CSP document; the main application never enables eval.
// TypeScript erases type-only imports. No vendor/application dependency is bundled here.
const source = await readFile(new URL('../src/runtime/dos/host.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText.replace(/^export /gm, '');
const hostJs = `${js}\ndosHost();\n`, jsHash = createHash('sha256').update(hostJs).digest('base64');
let html = await readFile(new URL('../src/runtime/dos/frame.html', import.meta.url), 'utf8');
const style = html.match(/<style>([\s\S]*?)<\/style>/)[1];
html = html.replace('STYLE_HASH', createHash('sha256').update(style).digest('base64')).replace('HOST_HASH', jsHash).replace('<script src="host.js"></script>', `<script>${hostJs}</script>`);
const htmlHash = createHash('sha256').update(html).digest('hex'), htmlName = `host-${htmlHash.slice(0, 16)}.html`;
for (const name of await readdir(new URL('../', root))) if (/^host(?:-[a-f0-9]+)?\.(js|html)$/.test(name)) await unlink(new URL(`../${name}`, root));
await writeFile(new URL(`../${htmlName}`, root), html);
await writeFile(new URL('../src/runtime/dos/host-manifest.ts', import.meta.url), `// Generated by scripts/runtime-assets.mjs from the audited application host source.\nexport const DOS_HOST_PATH = 'runtimes/js-dos/${htmlName}';\nexport const DOS_HOST_ASSETS = ${JSON.stringify({ [htmlName]: htmlHash }, null, 2)} as const;\n`);
// Sources/notices accompany local build outputs, but are never requested by the
// player. Runtime publication still requires the documented source rebuild gate.
const sources = new URL('../source/', root);
await mkdir(sources, { recursive: true });
for (const [path, entry] of Object.entries(manifest.retained)) {
  const bytes = await readFile(new URL(`../${path}`, import.meta.url));
  if (bytes.length !== entry.size || createHash('sha256').update(bytes).digest('hex') !== entry.sha256) throw new Error(`Audited source/fixture mismatch: ${path}`);
  if (path.startsWith('vendor/dos/')) await writeFile(new URL(path.slice('vendor/dos/'.length), sources), bytes);
}
await writeFile(new URL('manifest.json', sources), JSON.stringify(manifest, null, 2) + '\n');
await writeFile(new URL('../NOTICE.txt', root), await readFile(new URL('../vendor/dos/NOTICE.txt', import.meta.url)));
// The same previously audited fixtures are now explicitly selectable in Home.
const demoRoot = new URL('../public/demos/', import.meta.url);
await mkdir(demoRoot, { recursive: true });
for (const name of ['MEM.EXE', 'FREECOM.ZIP']) {
  const path = `tests/fixtures/dos/${name}`, bytes = await readFile(new URL(`../${path}`, import.meta.url));
  if (createHash('sha256').update(bytes).digest('hex') !== manifest.retained[path]?.sha256) throw new Error(`Demo fixture mismatch: ${name}`);
  await writeFile(new URL(name, demoRoot), bytes);
}
await writeFile(new URL('NOTICE.txt', demoRoot), 'FreeDOS MEM 1.12 and FreeCOM 0.86: GPL-licensed DOS fixtures.\nThese are real programs, not simulated output.\nFull notices: ../runtimes/js-dos/NOTICE.txt\nRetained sources, licenses and exact hashes: ../runtimes/js-dos/source/manifest.json\nSource packages and full license texts are served in that same source directory.\nPHANTOM remains a private local development build; see the repository license gate before public distribution.\n');

// Original application grant accompanies locally generated outputs.
await writeFile(new URL('../public/LICENSE.txt', import.meta.url), await readFile(new URL('../LICENSE', import.meta.url)));
